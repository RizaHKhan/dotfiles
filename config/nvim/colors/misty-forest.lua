for severity, color in pairs { Error = c.red, Warn = c.yellow, Info = c.blue, Hint = c.cyan, Ok = c.green } do
    groups["Diagnostic" .. severity] = { fg = color }
    groups["DiagnosticSign" .. severity] = { fg = color, bg = c.bg }
    groups["DiagnosticVirtualText" .. severity] = { fg = color, bg = c.black }
    groups["DiagnosticUnderline" .. severity] = { sp = color, undercurl = true }
end

for name, attrs in pairs(groups) do
    vim.api.nvim_set_hl(0, name, attrs)
end
for name, target in pairs(links) do
    vim.api.nvim_set_hl(0, name, { link = target })
end
